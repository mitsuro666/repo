"""Prepare lightweight browser data and a character-based webfont from local sources."""
from pathlib import Path
import html
import hashlib
import json
import os
import re
import sys

ROOT = Path(__file__).resolve().parent


def web_catalog(payload):
    works = []
    for work in payload['works']:
        language = work.get('language') or {}
        works.append({
            **{key: work[key] for key in ('rj', 'title', 'url', 'voice_actors')},
            'circle': {key: work['circle'].get(key, '') for key in ('id', 'name', 'url')},
            'bk': {key: work['bk'][key] for key in ('path', 'width', 'height') if key in work['bk']},
            'language': {key: language.get(key) for key in
                         ('is_chinese_version', 'chinese_subtitles', 'chinese_script')},
        })
    return {'metadata': {
        'schema_version': payload['metadata'].get('schema_version', 1),
        'count': len(works),
        'sources': [{'source_url': source['source_url']} for source in payload['metadata']['sources']],
    }, 'works': works}


def write_web_catalog(payload, data_dir):
    content = json.dumps(web_catalog(payload), ensure_ascii=False, separators=(',', ':'))
    content = content.replace('<', '\\u003c').replace('\u2028', '\\u2028').replace('\u2029', '\\u2029')
    path = data_dir / 'works.js'
    path.write_text('window.DLSITE_INTERSECTION = ' + content + ';\n', encoding='utf-8')
    return path


def unicode_ranges(codes):
    ranges = []
    start = end = None
    for code in sorted(codes):
        if start is None:
            start = end = code
        elif code == end + 1:
            end = code
        else:
            ranges.append(f'U+{start:X}' if start == end else f'U+{start:X}-{end:X}')
            start = end = code
    if start is not None:
        ranges.append(f'U+{start:X}' if start == end else f'U+{start:X}-{end:X}')
    return ','.join(ranges)


def build_webfont(payload):
    sys.path.insert(0, str(ROOT / '.build-tools'))
    from fontTools import subset
    from fontTools.ttLib import TTFont

    source = ROOT / 'font/BlackSugarPlumCandy-Bold.ttf'
    fallback = ROOT.parent.parent / 'font/black-sugar-plum-candy.woff2'
    font = TTFont(source, recalcTimestamp=False)
    supported = set(font.getBestCmap())
    full = TTFont(fallback)
    fallback_supported = set(full.getBestCmap())
    full.close()
    # The full project font is requested only for characters outside the page subset.
    text = json.dumps(web_catalog(payload), ensure_ascii=False)
    text += html.unescape((ROOT / 'index.html').read_text(encoding='utf-8'))
    codes = set(map(ord, text))
    for name in ('app.js', 'cart.js'):
        source_text = (ROOT / name).read_text(encoding='utf-8')
        codes.update(map(ord, source_text))
        for match in re.findall(r'cn\(([^)]*)\)', source_text):
            parts = [part.strip() for part in match.split(',')]
            if all(re.fullmatch(r'0x[0-9a-fA-F]+', part) for part in parts):
                codes.update(int(part, 16) for part in parts)
        codes.update(int(value, 16) for value in re.findall(r'\\u([0-9a-fA-F]{4})', source_text))
    for start, end in ((0x20, 0x100), (0x2000, 0x2070), (0x3000, 0x3100), (0xFF00, 0xFFF0)):
        codes.update(range(start, end))
    required = codes & supported
    remaining = supported - required
    if not remaining <= fallback_supported:
        raise ValueError('The full fallback font does not cover all remaining source characters')
    options = subset.Options()
    options.flavor = 'woff2'
    options.recalc_timestamp = False
    options.name_IDs = ['*']
    options.name_languages = ['*']
    options.name_legacy = True
    subsetter = subset.Subsetter(options=options)
    subsetter.populate(unicodes=required)
    subsetter.subset(font)
    output = ROOT / 'font/BlackSugarPlumCandy-web.woff2'
    font.flavor = 'woff2'
    font.save(output)
    font.close()
    # Static character coverage check; no browser rendering is performed.
    built = TTFont(output)
    assert required <= set(built.getBestCmap()), 'Webfont is missing required characters'
    built.close()
    fallback_url = os.path.relpath(fallback, output.parent).replace('\\', '/')
    def face(url, glyphs):
        return ('@font-face {\n  font-family: "BlackSugarPlumCandy";\n'
                f'  src: url("{url}") format("woff2");\n'
                '  font-weight: 700;\n  font-style: normal;\n  font-display: swap;\n'
                f'  unicode-range: {unicode_ranges(glyphs)};\n}}\n')
    css = '/* Generated by web_assets.py; keep character ranges separate. */\n'
    version = hashlib.sha256(output.read_bytes()).hexdigest()[:12]
    css += face(output.name + '?v=' + version, required)
    if remaining:
        css += face(fallback_url, remaining)
    (output.parent / 'webfont.css').write_text(css, encoding='utf-8')
    return {'source_bytes': source.stat().st_size, 'webfont_bytes': output.stat().st_size,
            'page_characters': len(required), 'fallback_characters': len(remaining)}


def main():
    data_dir = ROOT / 'data'
    payload = json.loads((data_dir / 'works.json').read_text(encoding='utf-8'))
    catalog = write_web_catalog(payload, data_dir)
    report = build_webfont(payload)
    report['browser_data_bytes'] = catalog.stat().st_size
    print(json.dumps(report))


if __name__ == '__main__':
    main()
